defmodule AshBpmn.NarrowedTest.Subscription do
  @moduledoc """
  A host's subscription: the macro's resource with the generated engine bypass left on, plus
  one action the host added and keeps for people (the shape of a "publish with authority"
  door). The host's own policy for it admits a person and nobody else.
  """

  use AshBpmn.Resources.Subscription,
    domain: AshBpmn.NarrowedTest.Domain,
    repo: AshBpmn.TestRepo,
    table: "tenant_bpmn_subscriptions",
    tenant?: true

  actions do
    update :publish_granted do
      accept []
      require_atomic? false
      change set_attribute(:status, :published)
    end
  end

  policies do
    policy action(:publish_granted) do
      authorize_if actor_attribute_equals(:person?, true)
    end
  end
end

defmodule AshBpmn.NarrowedTest.Domain do
  @moduledoc false
  use Ash.Domain, validate_config_inclusion?: false

  resources do
    resource AshBpmn.NarrowedTest.Subscription
  end
end

defmodule AshBpmn.EngineBypassScopeTest do
  @moduledoc """
  The generated engine bypass covers the doors the macro generated, and no others.

  A bypass authorizes everything after it, and a host's policies come after it. So while
  the bypass matched on the engine's mark alone, an action a host added to a generated
  resource and kept for people was open to anything carrying that mark. The host had to
  know to pass `policies?: false`; forgetting was silent.
  """

  use AshBpmn.DataCase, async: false

  alias AshBpmn.Checks.AshBpmnInteraction
  alias AshBpmn.NarrowedTest.Subscription
  alias AshBpmn.Scope

  @tenant Ecto.UUID.generate()

  setup do
    previous_source = Application.get_env(:ash_bpmn, :event_source)
    Application.put_env(:ash_bpmn, :event_source, TriggerTest.EventSource)
    TriggerTest.EventSource.reset!()

    on_exit(fn ->
      if previous_source,
        do: Application.put_env(:ash_bpmn, :event_source, previous_source),
        else: Application.delete_env(:ash_bpmn, :event_source)
    end)

    :ok
  end

  describe "an action the host added" do
    test "is refused to the engine's mark" do
      draft = draft!()

      assert {:error, %Ash.Error.Forbidden{}} =
               draft
               |> Ash.Changeset.for_update(:publish_granted, %{})
               |> Ash.update(engine())
    end

    test "is refused to the engine's mark even with a person's id beside it" do
      draft = draft!()

      assert {:error, %Ash.Error.Forbidden{}} =
               draft
               |> Ash.Changeset.for_update(:publish_granted, %{})
               |> Ash.update(engine(actor: %{id: Ecto.UUID.generate()}))
    end

    test "is open to whom the host's own policy admits" do
      draft = draft!()

      assert {:ok, %{status: :published}} =
               draft
               |> Ash.Changeset.for_update(:publish_granted, %{})
               |> Ash.update(actor: %{id: Ecto.UUID.generate(), person?: true}, tenant: @tenant)
    end
  end

  describe "the macro's own actions" do
    test "are still open to the engine's mark" do
      draft = draft!()

      assert {:ok, %{enabled: false}} =
               draft
               |> Ash.Changeset.for_update(:disable, %{})
               |> Ash.update(engine())
    end
  end

  describe "the engine action lists" do
    # A list that drifted from its macro would either leave a new engine action forbidden
    # to the engine, or (worse) keep naming an action the macro no longer generates, which
    # a host could then define for people and find open again.
    @kinds %{
      definition: AshBpmn.TenantTest.Definition,
      instance: AshBpmn.TenantTest.Instance,
      token: AshBpmn.TenantTest.Token,
      human_task: AshBpmn.TenantTest.HumanTask,
      task_candidate: AshBpmn.TenantTest.TaskCandidate,
      process_event: AshBpmn.TenantTest.ProcessEvent,
      timer_job: AshBpmn.TenantTest.TimerJob,
      signal: AshBpmn.TenantTest.Signal,
      subscription: AshBpmn.TenantTest.Subscription,
      cursor: AshBpmn.TenantTest.Cursor,
      dispatch: AshBpmn.TenantTest.Dispatch
    }

    test "name exactly the actions each macro generates" do
      for {kind, resource} <- @kinds do
        generated = resource |> Ash.Resource.Info.actions() |> Enum.map(& &1.name) |> Enum.sort()

        assert Enum.sort(AshBpmnInteraction.engine_actions(kind)) == generated,
               "#{inspect(resource)} (#{kind}) generates #{inspect(generated)}"
      end
    end

    test "condition every generated bypass" do
      for {kind, resource} <- @kinds do
        [bypass] = Ash.Policy.Info.policies(resource)

        assert Enum.any?(bypass.condition, fn
                 {AshBpmnInteraction, opts} ->
                   opts[:actions] == AshBpmnInteraction.engine_actions(kind)

                 _ ->
                   false
               end),
               "#{inspect(resource)}'s bypass should be limited to its generated actions"
      end
    end
  end

  defp engine(extra \\ []) do
    scope = Scope.engine(%Scope{tenant: @tenant})
    Keyword.merge(scope, extra)
  end

  defp draft! do
    Subscription
    |> Ash.Changeset.for_create(
      :create,
      %{
        key: "granted_#{System.unique_integer([:positive])}",
        match_resource: "TriggerTest.Payout",
        process_key: "p"
      }
    )
    |> Ash.create!(engine())
  end
end
